    for W_, H_, t in CHANNELS:
        u = usable(W_, H_, t)
        rows.append([f"{W_} × {H_}",
                     str(int(u // (3 * wire_area(1.5)))),
                     str(int(u // (3 * wire_area(2.5)))),
                     str(int(u // (3 * wire_area(4)))),
                     str(int(u // (3 * wire_area(6))))])
    return rows


