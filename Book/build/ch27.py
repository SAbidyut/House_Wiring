def wire_area(mm2):
    """একটি তারের বাইরের ক্ষেত্রফল, বর্গমিলিমিটারে।"""
    d = CABLE_OD[mm2]
    return math.pi / 4 * d * d


def inner(W_, H_, t):
    """চ্যানেলের ভেতরের চওড়া, উচ্চতা ও ক্ষেত্রফল।"""
    return W_ - 2 * t, H_ - 2 * t, (W_ - 2 * t) * (H_ - 2 * t)


def usable(W_, H_, t):
    return inner(W_, H_, t)[2] * SPACE_FACTOR / 100.0


def pick_channel(area_needed):
    """যে সবচেয়ে ছোট চ্যানেলে এই ক্ষেত্রফল 45%-এর ভেতরে ধরে।"""
    for W_, H_, t in CHANNELS:
        if W_ in PICK_FROM and usable(W_, H_, t) >= area_needed:
            return W_, H_, t
    return None


def _n(x, d=1):
    s = f"{x:.{d}f}"
    if d and s.endswith("0" * d):
        s = s[:-(d + 1)]
    return s


def size_rows():
    """সারণি ২৭.৩ — বাজারের মাপ, ভেতরের ক্ষেত্রফল ও ধারণক্ষমতা।"""
    rows = []
    for W_, H_, t in CHANNELS:
        w, h, a = inner(W_, H_, t)
        u = usable(W_, H_, t)
        rows.append([f"{W_} × {H_}", INCH_NAME.get(W_, "—"), _n(t, 1),
                     f"{_n(w, 1)} × {_n(h, 1)}", f"{a:.0f}", f"{u:.0f}",
                     str(int(u // wire_area(1.5))),
                     str(int(u // wire_area(2.5)))])
    return rows


def circuit_rows():
    """সারণি ২৭.৫ — কোন মাপে কয়টি সার্কিট (তিন-কোর ধরে)।"""
    rows = []
    for W_, H_, t in CHANNELS:
        u = usable(W_, H_, t)
        rows.append([f"{W_} × {H_}",
                     str(int(u // (3 * wire_area(1.5)))),
                     str(int(u // (3 * wire_area(2.5)))),
                     str(int(u // (3 * wire_area(4)))),
                     str(int(u // (3 * wire_area(6))))])
    return rows


