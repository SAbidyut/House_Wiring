def _n(x, d=2):
    """সংখ্যা — পেছনের অপ্রয়োজনীয় শূন্য ছেঁটে।

    অধ্যায় ২৪-এর ফাঁদ:  d == 0 হলে আগে 264-কে 26.4 বানিয়ে ফেলত।
    """
    if d == 0:
        return f"{round(x):d}"
    t = f"{x:.{d}f}".rstrip("0").rstrip(".")
    return t or "0"


def pick_size(mm2, cores, bends, length):
    """ক্যাবল ফ্যাক্টর কষে সবচেয়ে ছোট চলনসই কন্ডুইট।"""
    need = CF[mm2] * cores
    key = (bends, min([L for (b, L) in KF if b == bends and L >= length],
                      default=10))
    if key not in KF:
        key = (bends, 10)
    row = KF[key]
    for sz in PICK_FROM:
        if row[sz] >= need:
            return need, row, sz, key
    return need, row, None, key


def space_factor(mm2, n, size, cls=4):
    """n সংখ্যক তারে কত শতাংশ ভরাট — IS 9537-এর হেভি শ্রেণির ID ধরে।"""
    idd = dict((s[0], s[cls]) for s in PVC_SIZES)[size]
    a_pipe = math.pi / 4 * idd ** 2
    a_cab = math.pi / 4 * CABLE_OD[mm2] ** 2
    return n * a_cab / a_pipe * 100, a_pipe, a_cab


