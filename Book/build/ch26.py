def pvc_rows():
    return [[f"{s[0]}", f"{s[1]}", _n(s[2], 1), _n(s[3], 1), _n(s[4], 1),
             _n((s[1] - s[4]) / 2, 2)] for s in PVC_SIZES]


def kf_rows():
    out = []
    for (b, L) in sorted(KF, key=lambda k: (k[0], k[1])):
        head = ("সোজা" if b == 0 else ("এক বাঁক" if b == 1 else "দুই বাঁক"))
        out.append([f"{head} — {L} m"] + [f"{KF[(b, L)][s]}" for s in SIZES])
    return out


def cf_rows():
    return [[_n(k, 1), f"{v}"] for k, v in sorted(CF.items())]


def circuit_rows():
    rows = []
    for name, mm2, cores, L, b in CIRCUITS + [FEED]:
        need, row, sz, key = pick_size(mm2, cores, b, L)
        rows.append([name, f"{cores} × {_n(mm2, 1)}", f"{need}",
                     f"{L}", f"{b}", f"{row[sz]}", f"{sz} mm"])
    return rows


