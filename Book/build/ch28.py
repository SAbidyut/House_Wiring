def ecc(mm2):
    """BNBC সারণি ৮.১.২৭ + ধারা ১.৩.৩৭.৩.১-এর ইসিসি।"""
    if mm2 < 16:
        return max(4, mm2)
    if mm2 < 35:
        return 16
    return mm2 / 2


def r_of(mm2, length):
    """ওই দৈর্ঘ্যের পরিবাহীর রোধ, ওহমে (২০ ডিগ্রিতে)।"""
    return R20[mm2] * length / 1000.0


def r_rod(rho, L, d):
    """একক খাড়া রড বা পাইপের রোধ — BS 7430-এর সূত্র।"""
    return rho / (2 * math.pi * L) * (math.log(8 * L / d) - 1)


def r_plate(rho, side):
    """প্লেটের রোধ — IS 3043 ৯.২.১; A = দুই পিঠের ক্ষেত্রফল।"""
    return rho / 4 * math.sqrt(math.pi / (2 * side * side))


def _n(x, d=2):
    s = f"{x:.{d}f}"
    return s.rstrip("0").rstrip(".") if d else s


