def _meta_cache():
    fn = os.path.join(CACHE, "ch27_urls.json")
    return (json.load(open(fn)) if os.path.exists(fn) else {}), fn


def commons_meta(fname, width):
    """থাম্বনেইলের ঠিকানা ও ক্রেডিট।

    আসল ফাইল সরাসরি টানলে upload.wikimedia.org ৪২৯ ফেরত দেয় এবং নিজেই
    থাম্বনেইল ব্যবহার করতে বলে (অধ্যায় ২৬-এর শিক্ষা)।  তার-চিহ্ন
    হিসেবে **আসল ফাইলের** পিক্সেল-মাপ রাখা ও যাচাই করা হয়।
    """
    urls, fn = _meta_cache()
    key = f"{fname}|{width}"
    if key not in urls:
        q = urllib.parse.urlencode({
            "action": "query", "format": "json", "titles": "File:" + fname,
            "prop": "imageinfo", "iiprop": "url|size|extmetadata",
            "iiurlwidth": str(width)})
        d = json.loads(_get(API + "?" + q))
        page = next(iter(d["query"]["pages"].values()))
        if "imageinfo" not in page:
            raise SystemExit(f"✗ কমন্সে পাওয়া গেল না: {fname}")
        ii = page["imageinfo"][0]
        em = ii["extmetadata"]

        def _f(k):
            import re
            v = em.get(k, {}).get("value", "")
            return re.sub("<[^>]+>", "", v).strip()
        urls[key] = {"url": ii.get("thumburl") or ii["url"],
                     "size": [ii["width"], ii["height"]],
                     "artist": _f("Artist") or "অজ্ঞাত",
                     "licence": _f("LicenseShortName") or "?",
                     "page": "https://commons.wikimedia.org/wiki/File:"
                             + urllib.parse.quote(fname.replace(" ", "_"))}
        json.dump(urls, open(fn, "w"), ensure_ascii=False, indent=1)
        time.sleep(4)
    return urls[key]


def fetch_commons(fname, width):
    safe = "".join(c if c.isalnum() or c in "._-" else "_" for c in fname)
    fn = os.path.join(CACHE, f"ch27_{width}_{safe}")
    if not os.path.exists(fn) or os.path.getsize(fn) < 4096:
        open(fn, "wb").write(_get(commons_meta(fname, width)["url"]))
        time.sleep(12)
    return open(fn, "rb").read()


