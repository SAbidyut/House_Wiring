def amp_rows():
    """সারণি ২৩.১৫ — IEC 60364-5-52-এর সারণি B.52.2।"""
    return [[str(k) if k != int(k) else str(int(k))]
            + [str(v) for v in AMPACITY[k]] for k in AMPACITY]


def vdrop_rows():
    """সারণি ২৩.২০ — IEC 60228-এর রোধ থেকে হিসাব করা সহগ।"""
    rows = []
    for mm2 in (1.0, 1.5, 2.5, 4, 6, 10, 16, 25, 35):
        key = int(mm2) if mm2 == int(mm2) else mm2
        rows.append([
            str(key),
            f"{IEC60228[mm2][0]:.2f}".rstrip("0").rstrip("."),
            f"{r70(mm2):.2f}",
            f"{mv_per_am(mm2):.1f}",
            f"{mv_per_am(mm2, True):.1f}",
            f"{VD_LIMIT / 100 * V_PH / (10 * mv_per_am(mm2) / 1000):.0f}",
        ])
    return rows


def circuit_rows():
    """সারণি ২৩.২১ — ফ্ল্যাটের প্রতিটি সার্কিটের ক্যাবল যাচাই।

    কারেন্ট, ধারণক্ষমতা আর ভোল্টেজ ড্রপ — তিনটেই এখানেই হিসাব হয়,
    যাতে ছকের সংখ্যা আর অধ্যায় ২২-এর সংখ্যা কখনো আলাদা না হয়।
    """
    rows = []
    for name, watt, pf, mcb, cable, length in CIRCUITS:
        ib = watt / (V_PH * pf)
        cap = iz(cable, "B1", CA_DESIGN, CG[3])
        _v, pct = vdrop(ib, cable, length)
        key = int(cable) if cable == int(cable) else cable
        rows.append([name, _n(ib, 2), f"{mcb} A", str(key),
                     _n(cap, 1), str(length), _n(pct, 2) + "%",
                     "✔" if (ib <= mcb <= cap and pct <= VD_LIMIT) else "✘"])
    return rows


# BS 3737:1964-এর SWG — এক গাছি খেইয়ের ব্যাস ইঞ্চিতে।  মানটি
# প্রত্যাহৃত (BS 6722:1986 মেট্রিকে গেছে), তবু বাজারে ও বিএনবিসিতে
# সংখ্যাগুলো এখনো চলে।
SWG = {8: 0.160, 10: 0.128, 12: 0.104, 14: 0.080, 16: 0.064,
       18: 0.048, 20: 0.036, 22: 0.028, 24: 0.022, 26: 0.018}

# AWG জ্যামিতিক, সংজ্ঞাই সূত্র (ASTM B258):
#     d = 0.127 × 92^((36 − n)/39)  মিলিমিটারে
# হিসাবের ফল IEC 60228-এর ভূমিকার AWG ছকের সঙ্গে মিলে যায় —
# সেই মিলটাই যাচাই।
AWG_NOS = (20, 18, 16, 14, 12, 10, 8, 6, 4, 2)
METRIC = (0.5, 0.75, 1.0, 1.5, 2.5, 4, 6, 10, 16, 25, 35, 50)


def _area(d_mm):
    return math.pi / 4 * d_mm * d_mm


def _nearest_metric(a):
    """সবচেয়ে কাছের প্রচলিত মেট্রিক মাপ।"""
    m = min(METRIC, key=lambda x: abs(x - a))
    return str(int(m)) if m == int(m) else str(m)


def swg_rows():
    """সারণি — SWG নম্বর, ব্যাস ও ক্ষেত্রফল, সঙ্গে সাত খেইয়ের যোগফল।"""
    rows = []
    for n, inch in SWG.items():
        d = inch * 25.4
        a = _area(d)
        rows.append([str(n), f"{inch:.3f}", f"{d:.2f}", f"{a:.3f}",
                     f"{7 * a:.2f}"])
    return rows


def awg_rows():
    """সারণি — AWG নম্বর, ব্যাস, ক্ষেত্রফল ও কাছের মেট্রিক মাপ।"""
    rows = []
    for n in AWG_NOS:
        d = 0.127 * 92 ** ((36 - n) / 39)
        a = _area(d)
        rows.append([str(n), f"{d:.2f}", f"{a:.2f}", _nearest_metric(a)])
    return rows


def imperial_rows():
    """সারণি ২৩.১১ — পুরনো ইঞ্চি সংকেত ও বাজারের মাপ।

    ক্ষেত্রফলটা এখানেই কষা হয় (খেই × π/4 × ব্যাস বর্গ), মুখস্থ নয়।
    """
    data = [("1/0.044", 1, 0.044, "1.0", "1/1.13"),
            ("3/0.029", 3, 0.029, "1.3", "3/0.74"),
            ("1/0.056", 1, 0.056, "1.5", "1/1.38"),
            ("3/0.036", 3, 0.036, "2.0", "3/0.91"),
            ("7/0.029", 7, 0.029, "3.0", "7/0.74"),
            ("7/0.036", 7, 0.036, "4.5", "7/0.91"),
            ("7/0.044", 7, 0.044, "7.0", "7/1.12"),
            ("7/0.052", 7, 0.052, "9.5", "7/1.32"),
            ("7/0.064", 7, 0.064, "14.5", "7/1.63")]
    rows = []
    for name, n, d_in, market, metric in data:
        d_mm = d_in * 25.4
        area = n * math.pi / 4 * d_mm * d_mm
        rows.append([name.replace("/", " / ") + "″",
                     f"{d_mm:.2f}", f"{area:.2f}",
                     market, metric.replace("/", " / ")])
    return rows


