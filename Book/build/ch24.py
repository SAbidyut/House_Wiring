def mv_per_am(mm2):
    return 2 * r70(mm2)


def vdrop_pct(current, mm2, length):
    return current * mv_per_am(mm2) * length / 1000.0 / V_PH * 100


def iz(mm2, method=2, ca=CA35):
    return AMPACITY[mm2][method] * ca


def _n(x, d=1):
    """দশমিকের পর d ঘর, শেষের শূন্য ছেঁটে — ল্যাটিন অঙ্কে।

    d = 0 হলে ছাঁটা যাবে না:  `rstrip("0")` তখন 26400-কে 264 আর
    250-কে 25 বানিয়ে দেয়।  অধ্যায় ২৩ থেকে আসা এই সহায়কটি ওখানে
    কেবল d ≥ 1-এ ডাকা হতো, তাই বাগটি ধরা পড়েনি।
    """
    if d == 0:
        return f"{x:.0f}"
    return f"{x:.{d}f}".rstrip("0").rstrip(".")


def phase_kw(i):
    return (PHASE_FLATS[i] * FLAT_DEM + PHASE_COMMON[i] * 3.0 * 0.9
            + KW_3P_EACH)


PH_KW = [phase_kw(i) for i in range(3)]
