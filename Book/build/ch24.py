def riser_rows():
    """সারণি ২৪.৭ — তলা অনুযায়ী রাইজারের মাপ ও ড্রপ।"""
    rows = []
    for floor, length, cable in RISERS:
        pct = vdrop_pct(I_FLAT, cable, length)
        rows.append([str(floor), str(length), str(cable),
                     f"{iz(cable):.1f}", f"{pct:.2f}%",
                     f"{pct + VD_FINAL:.2f}%",
                     "✔" if pct + VD_FINAL <= VD_LIMIT else "✘"])
    return rows


